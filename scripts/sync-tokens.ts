// Pulls the design tokens out of the Home Assistant frontend and writes them
// as plain CSS to src/styles/tokens.css.
//
// The frontend keeps its tokens as Lit `css` template strings in TypeScript.
// Those are plain CSS inside a template literal, so we can lift them out
// without running any of the frontend code.
//
// Usage:
//   pnpm tokens                         # fetch from GitHub (dev branch)
//   pnpm tokens --from ../frontend      # read a local frontend checkout
//   pnpm tokens --ref some-branch       # fetch a different branch or tag

import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

const OUTPUT_FILE = new URL("../src/styles/tokens.css", import.meta.url);
const THEME_DIR = "src/resources/theme";

// Only the token layers. The legacy variables (--primary-color and friends)
// and the Web Awesome mapping stay behind on purpose.
const SOURCES = [
  { file: "core.globals.ts", lightExport: "coreStyles" },
  { file: "typography.globals.ts", lightExport: "typographyStyles" },
  {
    file: "semantic.globals.ts",
    lightExport: "semanticStyles",
    darkExport: "darkSemanticStyles",
  },
  { file: "color/core.globals.ts", lightExport: "coreColorStyles" },
  {
    file: "color/semantic.globals.ts",
    lightExport: "semanticColorStyles",
    darkExport: "darkSemanticColorStyles",
  },
];

const { values: options } = parseArgs({
  options: {
    from: { type: "string" },
    ref: { type: "string", default: "dev" },
  },
});

async function readSource(file: string) {
  if (options.from) {
    return readFile(path.join(options.from, THEME_DIR, file), "utf8");
  }

  const url = `https://raw.githubusercontent.com/home-assistant/frontend/${options.ref}/${THEME_DIR}/${file}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Fetching ${url} failed: ${response.status}`);
  }

  return response.text();
}

function describeSource() {
  if (!options.from) {
    return `home-assistant/frontend@${options.ref}`;
  }

  try {
    const commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      cwd: options.from,
      encoding: "utf8",
    }).trim();
    return `home-assistant/frontend@${commit} (local checkout)`;
  } catch {
    return "home-assistant/frontend (local checkout)";
  }
}

function extractCss(source: string, exportName: string, file: string) {
  const pattern = new RegExp(
    `export const ${exportName} = css\`([\\s\\S]*?)\`;`,
  );
  const match = source.match(pattern);
  if (!match) {
    throw new Error(`Could not find ${exportName} in ${file}`);
  }

  const css = match[1];

  // Interpolations mean the frontend started composing tokens in code.
  // Fail loudly instead of writing half a token set.
  if (css.includes("${")) {
    throw new Error(`${exportName} in ${file} contains an interpolation`);
  }

  return css.trim();
}

// The dark sets are a single `html { ... }` block. We need the declarations
// without the selector, so we can put them under our own dark mode selectors.
function extractDeclarations(css: string, exportName: string) {
  const match = css.match(/^html\s*\{([\s\S]*)\}$/);
  if (!match) {
    throw new Error(`${exportName} is not a single html { } block`);
  }

  return match[1].trim();
}

function indent(text: string, spaces: number) {
  const padding = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.trim() ? padding + line.trim() : ""))
    .join("\n");
}

const lightBlocks: string[] = [];
const darkDeclarations: string[] = [];

for (const source of SOURCES) {
  const content = await readSource(source.file);

  const lightCss = extractCss(content, source.lightExport, source.file);
  lightBlocks.push(
    `/* ${source.file}: ${source.lightExport} */\n${lightCss.replace(/\bhtml\s*\{/g, ":root {")}`,
  );

  if (source.darkExport) {
    const darkCss = extractCss(content, source.darkExport, source.file);
    darkDeclarations.push(
      `/* ${source.file}: ${source.darkExport} */\n${extractDeclarations(darkCss, source.darkExport)}`,
    );
  }
}

const dark = darkDeclarations.join("\n\n");

const output = `/*
 * Generated by scripts/sync-tokens.ts from ${describeSource()}.
 * Do not edit by hand, run \`pnpm tokens\` instead.
 */

${lightBlocks.join("\n\n")}

/* Dark mode: follows the system, unless the visitor picked a theme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent(dark, 4)}
  }
}

:root[data-theme="dark"] {
${indent(dark, 2)}
}
`;

await writeFile(OUTPUT_FILE, output);
console.log(`Wrote ${OUTPUT_FILE.pathname} from ${describeSource()}`);
